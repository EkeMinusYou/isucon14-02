#!/usr/bin/env python3
"""Generate host-specific TLS listeners from Taskfile topology."""
import argparse
import ipaddress
import pathlib
import re
import shutil

parser = argparse.ArgumentParser()
parser.add_argument('--hosts', nargs='+', required=True)
parser.add_argument('--matcher-hosts', nargs='+', required=True)
parser.add_argument('--forward-hosts', nargs='+', required=True)
parser.add_argument('--entry', required=True)
parser.add_argument('--entry-ip', required=True)
parser.add_argument('--port', type=int, required=True)
parser.add_argument('--interface', required=True)
parser.add_argument('--remote-home', required=True)
args = parser.parse_args()
hosts = dict(host.split('=', 1) for host in args.hosts)
if args.entry not in hosts or hosts[args.entry] != args.entry_ip:
    parser.error('entry must be one of the TLS endpoints with the same private IP')
if args.matcher_hosts != [args.entry]:
    parser.error('exactly one matcher must run on the entry host')
if args.forward_hosts != [args.entry]:
    parser.error('exactly one NAT entry must run on the entry host')
if len(hosts) != 2:
    parser.error('exactly two TLS endpoints are required')
if not 1 <= args.port <= 65535 or args.port == 443:
    parser.error('TLS backend port must differ from the direct matcher port')
for ip in hosts.values():
    ipaddress.IPv4Address(ip)
if len(set(hosts.values())) != len(hosts):
    parser.error('TLS endpoints must have distinct IPs')
if not re.fullmatch(r'[a-zA-Z0-9_-]+', args.interface):
    parser.error('invalid entry interface')
output = pathlib.Path('tools/contest/generated')
trees = output / 'nginx'
if trees.exists():
    shutil.rmtree(trees)
for host, ip in hosts.items():
    target = trees / host
    shutil.copytree('nginx', target, symlinks=True,
                    ignore=shutil.ignore_patterns('tls'))
    for default in (False, True):
        suffix = ' default_server' if default else ''
        lines = ["# GENERATED by 'task gen' -- do not edit",
                 f'listen {ip}:{args.port} ssl{suffix};']
        if host == args.entry:
            lines.append(f'listen 127.0.0.1:443 ssl{suffix};')
        name = 'tls-listen-default.conf' if default else 'tls-listen.conf'
        (target / name).write_text('\n'.join(lines) + '\n')

remote_ip = next(ip for host, ip in hosts.items() if host != args.entry)
mapping = ', '.join(f'{index} : {ip}'
                    for index, ip in enumerate(hosts.values()))
(output / 'isuride-tls.nft').write_text(f'''# GENERATED by 'task gen' -- do not edit
# Replace only our table atomically; retain all existing conntrack bindings.
add table ip isuride_tls
delete table ip isuride_tls
table ip isuride_tls {{
  chain prerouting {{
    type nat hook prerouting priority dstnat; policy accept;
    ip daddr {args.entry_ip} tcp dport 443 dnat to numgen inc mod 2 map {{ {mapping} }} : {args.port}
  }}
  chain output {{
    type nat hook output priority -100; policy accept;
    # Local entry-IP clients use the same path; 127.0.0.1:443 bypasses NAT.
    ip daddr {args.entry_ip} tcp dport 443 dnat to numgen inc mod 2 map {{ {mapping} }} : {args.port}
  }}
  chain postrouting {{
    type nat hook postrouting priority srcnat; policy accept;
    # Force remote replies through the entry, including same-subnet clients.
    ip daddr {remote_ip} tcp dport {args.port} ct original ip daddr {args.entry_ip} ct original proto-dst 443 snat to {args.entry_ip}
  }}
  chain forward {{
    type filter hook forward priority filter; policy drop;
    # Enabling forwarding must not turn this host into an unrestricted router.
    # Preserve related ICMP errors (including path MTU discovery).
    ct state related accept
    meta l4proto tcp ct status dnat ct original ip daddr {args.entry_ip} ct original proto-dst 443 ct state established accept
    ip daddr {remote_ip} tcp dport {args.port} ct status dnat ct original ip daddr {args.entry_ip} ct original proto-dst 443 accept
  }}
}}
''')
(output / 'isuride-tls.sysctl').write_text(f'''# GENERATED by 'task gen' -- do not edit
net.ipv4.ip_forward = 1
# Both backends share the entry interface; never suggest a direct return path.
net.ipv4.conf.all.send_redirects = 0
net.ipv4.conf.default.send_redirects = 0
net.ipv4.conf.{args.interface}.send_redirects = 0
''')
(output / 'isuride-tls-forward.service').write_text(f'''# GENERATED by 'task gen' -- do not edit
[Unit]
Description=ISURIDE kernel TCP connection distribution
Wants=network-online.target
After=network-online.target systemd-sysctl.service nftables.service ufw.service
Before=nginx.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStartPre=/usr/sbin/sysctl -p {args.remote_home}/isuride-tls.sysctl
ExecStart=/usr/sbin/nft -f {args.remote_home}/isuride-tls.nft
ExecReload=/usr/sbin/nft -f {args.remote_home}/isuride-tls.nft
ExecStop=/usr/sbin/nft delete table ip isuride_tls

[Install]
WantedBy=multi-user.target
''')
